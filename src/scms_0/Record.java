    private void populatechecks() {
    if (conn == null) {
        JOptionPane.showMessageDialog(null, "Failed to connect to database.");
        return;
    }
    String checkInInfoQuery = "SELECT * FROM check_ins " +
         "ORDER BY check_in_time DESC";
    try (PreparedStatement psCheckInInfo = conn.prepareStatement(checkInInfoQuery)) {
        try (ResultSet rsCheckInInfo = psCheckInInfo.executeQuery()) {
            DefaultTableModel model = (DefaultTableModel) checkUpTable1.getModel();
            model.setRowCount(0);

            while (rsCheckInInfo.next()) {
                String idNumber = rsCheckInInfo.getString("id_number");
                String reason = rsCheckInInfo.getString("reason");
                String purpose = rsCheckInInfo.getString("purpose");
                String dateTime = rsCheckInInfo.getString("check_in_time");
                model.addRow(new Object[]{idNumber, reason, purpose, dateTime});
            }
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(null, "An error occurred while retrieving check-in information. Please try again later.");
    } finally {
        try {
            if (rs!= null) {
                rs.close();
            }
            if (ps!= null) {
                ps.close();
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, ex.getMessage());
        }
    }
    }
    private void populatepatients() {
        if (conn == null) {
            JOptionPane.showMessageDialog(null, "Failed to connect to database.");
            return;
        }
        try {
            String sql = "SELECT role, id_number, last_name, first_name, date_of_birth, occupation, allergies, medical_condition, contact_no, emergency_no " +
                    "FROM records";

            ps = conn.prepareStatement(sql);
            rs = ps.executeQuery();

            DefaultTableModel model = (DefaultTableModel) patientTable.getModel();
            model.setRowCount(0);
            while (rs.next()) {
                String role = rs.getString("role");
                String idNumber = rs.getString("id_number");
                String lastName = rs.getString("last_name");
                String firstName = rs.getString("first_name");
                Date dob = rs.getDate("date_of_birth");
                String occupation = rs.getString("occupation");
                String allergies = rs.getString("allergies");
                String medicalCondition = rs.getString("medical_condition");
                String contactNo = rs.getString("contact_no");
                String emergencyNo = rs.getString("emergency_no");

                model.addRow(new Object[]{role, idNumber, firstName, lastName, occupation, dob, medicalCondition, allergies, contactNo, emergencyNo});
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Error: " + ex.getMessage());
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, "Error closing resources: " + ex.getMessage());
            }
        }
    }
