    private void confirmButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmButtonActionPerformed
        if (conn == null) {
            JOptionPane.showMessageDialog(null, "Database connection failed. Please check your database settings.");
            return;
        }
        if (txtIdNum.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "ID Number is empty");
            return; 
        } else if (txtReason.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Reason is empty");
            return; 
        } else if ("-Select Purpose-".equals(jComboBox1.getSelectedItem())) {
            JOptionPane.showMessageDialog(null, "Purpose is empty");
            return; 
        }

        String id_number = txtIdNum.getText();

        String checkPatientExistsSql = "SELECT COUNT(*) FROM patients WHERE id_number = ?";
        try (PreparedStatement psCheck = conn.prepareStatement(checkPatientExistsSql)) {
            psCheck.setString(1, id_number);
            ResultSet rs = psCheck.executeQuery();
            if (rs.next()) {
                int count = rs.getInt(1);
                if (count == 0) {
                    String insertPatientSql = "INSERT INTO patients (id_number, is_active) VALUES (?, TRUE)";
                    try (PreparedStatement psInsert = conn.prepareStatement(insertPatientSql)) {
                        psInsert.setString(1, id_number);
                        psInsert.executeUpdate();

                        String insertRecordSql = "INSERT INTO records (id_number) VALUES (?)";
                        try (PreparedStatement psInsertRecord = conn.prepareStatement(insertRecordSql)) {
                            psInsertRecord.setString(1, id_number);
                            psInsertRecord.executeUpdate();
                        }
                    }
                } else {
                    // Patient exists, update is_active to TRUE
                    String updatePatientSql = "UPDATE patients SET is_active = TRUE WHERE id_number = ?";
                    try (PreparedStatement psUpdate = conn.prepareStatement(updatePatientSql)) {
                        psUpdate.setString(1, id_number);
                        psUpdate.executeUpdate();
                    }
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "An error occurred while checking the patient. Please try again later.");
            return;
        }

        // Proceed with check-in insertion
        String sql = "INSERT INTO check_ins (id_number, reason, purpose) VALUES (?, ?, ?)";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, id_number);
            ps.setString(2, txtReason.getText());
            ps.setString(3, jComboBox1.getSelectedItem().toString());
            ps.executeUpdate();
            String message = "Check-In Successful. \nYour ID Number is: " + id_number;
            JOptionPane.showMessageDialog(null, message);
            Info info = new Info(id_number);
            info.setVisible(true);
            dispose();
            // Navigate to next frame if needed
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "An error occurred while processing your check-in. Please try again later.");
        }
    }//GEN-LAST:event_confirmButtonActionPerformed

