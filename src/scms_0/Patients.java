    private void removeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeButtonActionPerformed
        int selectedRowIndex = infoTable.getSelectedRow();

        if (selectedRowIndex != -1) {
            // Retrieve the ID number of the selected row
            String idNumber = (String) infoTable.getValueAt(selectedRowIndex, 1); // Assuming ID number is in the second column

            // Execute an update query to set is_active to false for the selected patient
            try {
                String sql = "UPDATE patients SET is_active = false WHERE id_number = ?";
                ps = conn.prepareStatement(sql);
                ps.setString(1, idNumber);
                ps.executeUpdate();

                // Optionally, you can show a success message or update the table
                JOptionPane.showMessageDialog(null, "Patient removed successfully");

                // Clear the text fields and combo box
                txtIdNum.setText("");
                txtFirstName.setText("");
                txtLastName.setText("");
                txtDob.setDate(null);
                txtEme.setText("");
                txtCon.setText("");
                jComboBox1.setSelectedItem("-Select Role-");
                txtAllergies.setText("");
                txtHeart.setSelected(false);
                txtAsthma.setSelected(false);
                txtSeizure.setSelected(false);
                txtDiabetes.setSelected(false);
                txtOthers.setText("");
                txtProg.setText("");
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, ex.getMessage());
            } finally {
                try {
                    if (ps != null) {
                        ps.close();
                    }
                } catch (SQLException ex) {
                    JOptionPane.showMessageDialog(null, ex.getMessage());
                }
            }
        } else {
            JOptionPane.showMessageDialog(null, "Please select a patient to remove");
        }
    }//GEN-LAST:event_removeButtonActionPerformed

