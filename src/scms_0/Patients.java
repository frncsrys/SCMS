    private void populatePatientTable() {
    try {
        String sql = "SELECT * FROM patients WHERE is_active = true";
        ps = conn.prepareStatement(sql);
        rs = ps.executeQuery();

        DefaultTableModel model = (DefaultTableModel) infoTable.getModel();
        model.setRowCount(0); 
        while (rs.next()) {
            jComboBox1.setSelectedItem("-Select Role-");
            String role = rs.getString("role"); // Assuming 'role' is one of the columns in your table
            String idNumber = rs.getString("id_number");
            String firstName = rs.getString("first_name");
            String lastName = rs.getString("last_name");
            String occupation = rs.getString("occupation");
            Date dob = rs.getDate("date_of_birth");
            String medicalCondition = rs.getString("medical_condition"); 
            txtHeart.setSelected(false);
            txtAsthma.setSelected(false);
            txtSeizure.setSelected(false);
            txtDiabetes.setSelected(false);
            txtOthers.setText("");
            if (medicalCondition!= null) {
                String[] conditions = medicalCondition.split(" ");
                for (String condition : conditions) {
                    if (condition.equals("Heart")) {
                        txtHeart.setSelected(true); 
                    } else if (condition.equals("Asthma")) {
                        txtAsthma.setSelected(true);
                    } else if (condition.equals("Seizure")) {
                        txtSeizure.setSelected(true);
                    } else if (condition.equals("Diabetes")) {
                        txtDiabetes.setSelected(true);
                    } else {
                        txtOthers.setText(txtOthers.getText().trim() + " " + condition);
                    }
                }
            }           
            String allergy = rs.getString("allergies");
            String contactNo = rs.getString("contact_no");
            String emergency = rs.getString("emergency_no");

            model.addRow(new Object[]{role, idNumber, firstName, lastName, occupation, dob, medicalCondition, allergy, contactNo, emergency});
        }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, ex.getMessage());
        } finally {
            try {
                if (rs!= null) {
                    rs.close();
                }
                if (ps!= null) {
                    ps.close();
                }
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, ex.getMessage());
            }
        }
    }


